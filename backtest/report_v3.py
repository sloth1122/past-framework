#!/usr/bin/env python3
"""Summarise backtest_v3 JSON outputs into a markdown report (docs/BACKTEST_V3_RESULTS.md).

Usage: python3 report_v3.py <base.json> [--sens label=path.json ...]
Every number in the paper's results section must come from this file.
"""
import argparse, collections, json, os

ROOT = os.path.realpath(os.path.join(os.path.dirname(__file__), ".."))
# JSON inputs may only come from the repo or the backtest output directory.
INPUT_ROOTS = [ROOT, os.path.realpath(os.path.expanduser(
    os.environ.get("OUT_DIR", "~/trading-arena/state/backtests")))]


def _inside(path, roots):
    return any(os.path.commonpath([path, r]) == r for r in roots)


def safe_input(p):
    """Resolve a CLI-supplied path or glob to one .json file under INPUT_ROOTS."""
    import glob
    p = os.path.expanduser(p)
    hits = sorted(glob.glob(p)) if any(c in p for c in "*?[") else [p]
    if not hits:
        raise FileNotFoundError(p)
    real = os.path.realpath(hits[-1])
    if not real.endswith(".json") or not _inside(real, INPUT_ROOTS):
        raise ValueError(f"refusing input outside {INPUT_ROOTS} or not .json: {real}")
    return real


def load(p):
    with open(safe_input(p)) as f:
        return json.load(f)

def money(x):
    return f"{'+' if x >= 0 else '−'}${abs(x):,.2f}"

def pct(x):
    return f"{'+' if x >= 0 else '−'}{abs(x):.2f}%"

def agent_row(k, r):
    wr = f"{r['win_rate']*100:.0f}%" if r["win_rate"] is not None else "—"
    return (f"| {k} | ${r['final_equity']:,.2f} | {pct(r['total_return_pct'])} | {money(r['realized_pnl'])} | "
            f"{money(r['unrealized_pnl'])} | {r['closed_trades']} | {len(r['open_at_end'])} | {wr} | "
            f"−{abs(r['max_drawdown_pct']):.1f}% | {r['judge_approved']}/{r['judge_signals']} | {r.get('approved_but_no_cash',0)} | {r.get('filled_entries', r['judge_approved'])} |")

HDR = ("| Agent | Final equity | Return | Realized | Unrealized | Closed | Open at end | Win rate (closed) | Max DD | Judge approved/signals | Approved, no cash | Filled |\n"
       "|---|---|---|---|---|---|---|---|---|---|---|---|")

def per_ticker(r):
    pt = collections.defaultdict(lambda: {"closed": 0, "realized": 0.0, "unrealized": 0.0})
    for t in r["trades"]:
        pt[t["ticker"]]["closed"] += 1; pt[t["ticker"]]["realized"] += t["pnl"]
    for o in r["open_at_end"]:
        pt[o["ticker"]]["unrealized"] += o["unrealized"]
    return pt

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("base")
    ap.add_argument("--sens", nargs="*", default=[])
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "docs", "BACKTEST_V3_RESULTS.md"))
    a = ap.parse_args()
    d = load(a.base)
    R = d["results"]
    L = []
    L.append("# Backtest v3 Results — portfolio-level, shared capital\n")
    L.append(f"Generated by `backtest/report_v3.py` from `{os.path.basename(a.base)}`. Do not edit numbers by hand — re-run `backtest_v3.py` then `report_v3.py` and commit both the JSON and this file together.\n")
    L.append("## Configuration\n")
    L.append("| Parameter | Value |\n|---|---|")
    L.append(f"| Window | {d['start']} → {d['end']} |")
    L.append(f"| Tickers | {', '.join(d['tickers'])} |")
    L.append(f"| Capital | ${d['alloc_per_agent']:,.0f} per agent, one shared cash pool across all tickers |")
    L.append(f"| Fills | {d['fills']} |")
    L.append(f"| Indicators | rolling 52-week window; every value at day D uses only D−252…D |")
    L.append(f"| Stop re-entry cooldown | {d['stop_cooldown_days']} trading day(s) |")
    L.append(f"| IPO ban (Judge 11c) | {'ON — no entries < 90 days public' if d['ipo_ban'] else 'OFF'} |")
    L.append(f"| Judge | {d['judge']} |")
    L.append("| Rocky | rule-based, every 10 trading days, reacts only to trades closed since the previous review, ±1 trust region; only Alpha Entry Patience has a defined rule cascade |\n")

    L.append("## Headline\n")
    L.append(HDR)
    for k, r in R.items():
        L.append(agent_row(k, r))
    a_, bb, ba = R["alpha"], R.get("beta_baker"), R.get("beta_aschenbrenner")
    if bb:
        tot = a_["final_equity"] + bb["final_equity"]
        L.append(f"| **Alpha + Beta (Baker, live profile)** | **${tot:,.2f}** | **{pct((tot/5000-1)*100)}** | | | | | | | | | |")
    if ba:
        tot = a_["final_equity"] + ba["final_equity"]
        L.append(f"| Alpha + Beta (Aschenbrenner, paper §6.3 config) | ${tot:,.2f} | {pct((tot/5000-1)*100)} | | | | | | | | | |")
    L.append("")
    L.append("Win rate is computed on closed trades only. Beta's only exit rule is a stop-loss, so **every closed Beta trade is a loss by construction**; Beta's gains exist only as open, unrealized positions at the end of the window. Win rate is therefore not a meaningful statistic for Beta.\n")

    for k, r in R.items():
        L.append(f"## {k} — {r['label']}\n")
        L.append("### Per-ticker\n")
        L.append("| Ticker | Closed trades | Realized | Unrealized (open at end) |\n|---|---|---|---|")
        for tk in d["tickers"]:
            v = per_ticker(r).get(tk)
            if v is None:
                L.append(f"| {tk} | 0 | — | — |")
            else:
                L.append(f"| {tk} | {v['closed']} | {money(v['realized'])} | {money(v['unrealized']) if v['unrealized'] else '—'} |")
        L.append("")
        L.append("### Closed trades\n")
        L.append("| Entry | Exit | Ticker | Entry px | Exit px | Shares | P&L | Reason |\n|---|---|---|---|---|---|---|---|")
        for t in r["trades"]:
            L.append(f"| {t['entry_date']} | {t['exit_date']} | {t['ticker']} | {t['entry_price']:.2f} | {t['exit_price']:.2f} | {t['shares']} | {money(t['pnl'])} | {t['exit_reason']} |")
        if r["open_at_end"]:
            L.append("\n### Open at end of window (marked at last close)\n")
            L.append("| Entry | Ticker | Entry px | Mark | Shares | Unrealized |\n|---|---|---|---|---|---|")
            for o in r["open_at_end"]:
                L.append(f"| {o['entry_date']} | {o['ticker']} | {o['entry_price']:.2f} | {o['mark']:.2f} | {o['shares']} | {money(o['unrealized'])} |")
        L.append("\n### PAST score evolution (Rocky)\n")
        L.append("| Cycle | Date | Scores | Adjustment | Reason |\n|---|---|---|---|---|")
        for h in r["past_history"]:
            L.append(f"| {h['cycle']} | {h.get('date','start')} | {h['scores']} | {h.get('adjustments','')} | {'; '.join(h['reasons'])} |")
        rej = collections.Counter()
        for v in r["verdicts"]:
            if not v["approved"]:
                for n in v["notes"]:
                    if not n.startswith("✗"):
                        continue
                    if "public" in n:
                        rej["IPO ban (<90 days public)"] += 1
                    elif "banned list" in n:
                        rej["agent restricted list"] += 1
                    elif "open positions" in n:
                        rej["max positions"] += 1
                    else:
                        rej[n[2:]] += 1
        nocash = r.get("approved_but_no_cash", 0)
        L.append(f"\n### Judge\n\n{r['judge_signals']} entry signals, {r['judge_approved']} approved, {r['judge_rejected']} rejected. "
                 f"Of the approvals, {nocash} could not be filled because the agent had no free cash (fully deployed); {r.get('filled_entries', r['judge_approved'])} became positions. "
                 f"Rejection causes: {dict(rej) if rej else 'none'}.\n")

    if a.sens:
        L.append("## Sensitivity\n")
        L.append("| Run | Alpha | Beta (Baker) | Beta (Aschenbrenner) | Alpha + Baker |\n|---|---|---|---|---|")
        def line(label, dd):
            x = dd["results"]
            al, bk, asch = x["alpha"], x.get("beta_baker"), x.get("beta_aschenbrenner")
            tot = al["final_equity"] + bk["final_equity"] if bk else float("nan")
            return (f"| {label} | {pct(al['total_return_pct'])} | {pct(bk['total_return_pct']) if bk else '—'} | "
                    f"{pct(asch['total_return_pct']) if asch else '—'} | {pct((tot/5000-1)*100)} |")
        L.append(line(f"**Base** (cooldown {d['stop_cooldown_days']}, IPO ban {'on' if d['ipo_ban'] else 'off'})", d))
        for s in a.sens:
            label, path = s.split("=", 1)
            L.append(line(label, load(path)))
        L.append("")
        L.append("Cooldown semantics: 0 = a ticker stopped at session D may be re-entered at D+1 (live-matching); N = N further sessions must pass; −1 = same-bar re-entry (v1 artifact). Beta's result is dominated by whether MU is re-entered on 2026-03-31 ($337.79) or not until 2026-06-10 ($891.74); see paper §7.6.\n")

    out = os.path.realpath(a.out)
    if not out.endswith(".md") or not _inside(out, [ROOT]):
        raise SystemExit(f"--out must be a .md file inside the repo: {out}")
    with open(out, "w") as f:
        f.write("\n".join(L))
    print(f"wrote {out}")

if __name__ == "__main__":
    main()
